interface DocumentBlock {
	readonly node: UiNode;
	above: UiNode | undefined;
	lead: number;
	body: number | undefined;
	block: Block | undefined;
}

interface Document {
	readonly width: number;
	readonly nodes: readonly UiNode[];
	readonly blocks: readonly DocumentBlock[];
	readonly byNode: ReadonlyMap<UiNode, number>;
	readonly rows: TranscriptRows;
	/** New, not-yet-laid-out nodes; older widths supply estimates, not painted blocks. */
	remaining: number;
	warmup: number;
	seeded: boolean;
}

const OVERSCAN = 4;
const REFINE_BLOCKS = 32;
const REFINE_MS = 4;
const AUTO_SCROLL_MS = 80;
const MULTI_CLICK_MS = 500;
const WORD_CELL = /[\p{L}\p{N}\p{M}'’‐‑_./\\:?&=%#@~+-]/u;
const CJK_CELL = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u;

/** A row and column inside a node, independent of other nodes' heights. Negative rows are its separator. */
interface Point extends Cell {
	readonly node: UiNode;
}

/** A remounted document has fresh nodes; its stable block order locates the old point. */
interface Bookmark {
	readonly index: number;
	readonly kind: UiNode["kind"];
	readonly width: number;
	readonly row: number;
	readonly textOffset: number | undefined;
}

interface Selection<T extends Cell = Point> {
	readonly anchor: T;
	readonly focus: T;
	/** A multi-click can select even a single cell without a drag. */
	readonly explicit?: boolean;
}

interface Dock {
	readonly top: number;
	readonly rows: readonly string[];
	readonly textRows: readonly (TextRow | undefined)[];
}

interface View {
	readonly document: Document;
	readonly top: number;
	readonly from: number;
	readonly to: number;
	readonly maxTop: number;
	readonly railCol: number;
	readonly railRows: number;
	readonly thumbTop: number;
	readonly thumbRows: number;
	readonly returnRow: number;
}

export interface ViewportHit {
	readonly hit: Hit;
	readonly top: number;
	readonly left: number;
	/** The dock begins here; this hit in `main` must not extend into it. */
	readonly clipAt?: number;
	/** A sheet masks lower hits even in parts that are not interactive. */
	readonly occludes?: boolean;
}

interface AppViewportOptions {
	readonly surface: Surface;
	readonly paint: (node: UiNode, width: number, layoutOnly?: boolean) => Block;
	readonly separator: (above: UiNode, below: UiNode) => number;
	readonly theme: () => Theme;
	readonly requestRender: () => void;
	readonly copy: (text: string) => void;
	readonly paste?: () => void;
}

function pointAt(document: Document, row: number, col: number): Point {
	const index = document.rows.find(row);
	const entry = document.blocks[index]!;
	const relative = row - document.rows.start(index) - entry.lead;
	const text = entry.block?.rows[relative];
	return {
		node: entry.node,
		row: relative,
		col: relative < 0 ? 0 : text === undefined ? col : Math.min(col, visibleWidth(text)),
	};
}

const SIZED = "\x1b]66;";
/** The cursor-up wrapper generated by the image store for placements anchored on their last row. */
const IMAGE_ANCHOR = /\x1b7\x1b\[(\d+)A[\s\S]*?\x1b8/g;

function sizedText(span: string): string {
	return span.slice(span.indexOf(";", SIZED.length) + 1, span.endsWith("\x07") ? -1 : -2);
}

/** Text on screen, excluding escape payloads except the visible text of OSC 66 spans. */
function plainText(line: string): string {
	if (!line.includes(SIZED)) return stripEscapes(line);
	return tokens(line)
		.map(token => (token.text.startsWith(SIZED) ? sizedText(token.text) : token.escape ? "" : token.text))
		.join("");
}

/** Spaces can be padding or wrap boundaries; they do not move the text anchor. */
function contentLength(line: string): number {
	return plainText(line).replace(/\s+/gu, "").length;
}

function textOffsetAt(rows: readonly string[], { row, col }: Cell): number {
	let offset = contentLength(sliceColumns(rows[row] ?? "", 0, col));
	for (let i = 0; i < row && i < rows.length; i++) offset += contentLength(rows[i]!);
	return offset;
}

function cellAtTextOffset(rows: readonly string[], offset: number, keepColumn = false): Cell {
	let row = 0;
	let col = 0;
	for (; row < rows.length - 1; row++) {
		const length = contentLength(rows[row]!);
		if (offset < length) break;
		offset -= length;
	}
	if (keepColumn && offset > 0) {
		for (const piece of pieces(rows[row]!)) {
			if (piece.escape) continue;
			const length = contentLength(piece.text);
			if (length > offset) break;
			offset -= length;
			col += piece.width;
		}
	}
	return { row, col };
}

/** Rebase a block-relative point when the block between the same nodes is repainted. */
function rebase(point: Point, before: Document, after: Document, keepColumn = false): Point | undefined {
	const index = after.byNode.get(point.node);
	if (index === undefined) return undefined;
	const current = after.blocks[index]!;
	if (!current.block?.rows.length) return undefined;
	const previousIndex = before.byNode.get(point.node);
	const previous = previousIndex === undefined ? undefined : before.blocks[previousIndex]?.block;
	let row = point.row;
	let col = point.col;
	if (row >= 0 && previous && before.width !== after.width && previous.rows !== current.block.rows) {
		// Keep the text at the top (or under the selected cell), not the old wrap row. This
		// is approximate for a painter whose decoration or content changes at the new width.
		// Snap selection columns to grapheme starts before measuring the prefix.
		({ row, col } = cellAtTextOffset(current.block.rows, textOffsetAt(previous.rows, point), keepColumn));
	}
	row = Math.max(-current.lead, Math.min(row, current.block.rows.length - 1));
	return { node: point.node, row, col: Math.min(col, visibleWidth(current.block.rows[row] ?? "")) };
}

/** Selection endpoints in document order, or undefined for an ordinary click. */
function ordered(selection: Selection | undefined, document: Document): readonly [Point, Point] | undefined {
	if (!selection) return undefined;
	const { anchor, focus } = selection;
	const first = document.byNode.get(anchor.node);
	const last = document.byNode.get(focus.node);
	if (first === undefined || last === undefined) return undefined;
	if (first !== last) return first < last ? [anchor, focus] : [focus, anchor];
	return orderCells(selection);
}

function orderCells<T extends Cell>(selection: Selection<T>): readonly [T, T] | undefined {
	const { anchor, focus } = selection;
	if (!selection.explicit && anchor.row === focus.row && anchor.col === focus.col) return undefined;
	return anchor.row < focus.row || (anchor.row === focus.row && anchor.col < focus.col)
		? [anchor, focus]
		: [focus, anchor];
}

function position(document: Document, point: Point): Cell {
	const index = document.byNode.get(point.node)!;
	return { row: document.rows.start(index) + document.blocks[index]!.lead + point.row, col: point.col };
}

/** Selected cells, including the last clicked cell and without slicing through wide glyphs. */
function columns(line: string, row: number, start: Cell, end: Cell, textRow?: TextRow): [number, number] {
	const first = textRow?.start ?? 0;
	const last = textRow?.end ?? visibleWidth(line);
	const from = row === start.row ? Math.max(first, start.col) : first;
	const to = row === end.row ? Math.min(last, end.col + 1) : last;
	let left = from;
	let right = to;
	let col = 0;
	for (const piece of pieces(line)) {
		const next = col + piece.width;
		if (col < from && from < next) left = col;
		if (col < to && to < next) right = next;
		col = next;
		if (col >= to) break;
	}
	return [left, right];
}

function highlight(line: string, row: number, start: Cell, end: Cell, textRow?: TextRow): string {
	if (row < start.row || row > end.row || hasGraphics(line)) return line;
	const [left, right] = columns(line, row, start, end, textRow);
	const selected = sliceColumns(line, left, right);
	if (!selected) return line;
	// Drop selected text's styles so an embedded reset cannot cancel the highlight.
	const body = selected.includes(SIZED)
		? tokens(selected)
				.filter(token => !token.escape || token.text.startsWith(SIZED))
				.map(token => token.text)
				.join("")
		: stripEscapes(selected);
	return `${sliceColumns(line, 0, left)}\x1b[7m${body}\x1b[0m${sliceColumns(line, right, visibleWidth(line))}`;
}

function appendSelection(
	chunks: string[],
	line: string,
	row: number,
	start: Cell,
	end: Cell,
	textRow: TextRow | undefined,
): void {
	if (chunks.length > 0) chunks.push(textRow?.join ?? "\n");
	if (hasGraphics(line)) {
		chunks.push("");
		return;
	}
	const [left, right] = columns(line, row, start, end, textRow);
	const text = plainText(sliceColumns(line, left, right));
	chunks.push(textRow === undefined && right >= visibleWidth(line) ? text.trimEnd() : text);
}

function clickRange(
	line: string,
	col: number,
	count: number,
	textRow?: TextRow,
): readonly [number, number] | undefined {
	const start = textRow?.start ?? 0;
	const end = textRow?.end ?? visibleWidth(line);
	if (end <= start || hasGraphics(line)) return undefined;
	if (count >= 3) return [start, end - 1];
	if (count !== 2 || col < start || col >= end) return undefined;
	const spans: { start: number; end: number; kind: string }[] = [];
	let at = 0;
	for (const piece of pieces(line)) {
		if (piece.width === 0) continue;
		const next = at + piece.width;
		if (at >= start && next <= end) {
			const kind = /^\s+$/u.test(piece.text)
				? "blank"
				: CJK_CELL.test(piece.text)
					? "cjk"
					: WORD_CELL.test(piece.text)
						? "word"
						: "other";
			const last = spans.at(-1);
			if (last?.kind === kind) last.end = next;
			else spans.push({ start: at, end: next, kind });
		}
		at = next;
	}
	const word = spans.find(span => col >= span.start && col < span.end);
	return word && word.kind !== "blank" ? [word.start, word.end - 1] : undefined;
}

/** The ANSI `main` region's scroll and selection, independent of dock and layer layout. */
export class AppViewport {
	#layout: Document | undefined;
	#view: View | undefined;
	/** Undefined follows the transcript tail. */
	#anchor: Point | undefined;
	#scrollScope: MainScrollScope | undefined;
	readonly #bookmarks = new Map<string, Bookmark>();
	#selection: Selection | undefined;
	#dock: Dock | undefined;
	#dockSelection: Selection<Cell> | undefined;
	#lastClick: { readonly point: Cell | Point; readonly time: number; readonly count: number } | undefined;
	#edge: { readonly row: number; readonly col: number; readonly delta: number } | undefined;
	#autoScroll: Timer | undefined;
	#dragging = false;
	#scrollbarGrab: number | undefined;

	constructor(private readonly options: AppViewportOptions) {}

	#document(width: number): Document {
		const nodes = this.options.surface.main();
		const previous = this.#layout;
		if (previous?.width === width && previous.nodes === nodes) return previous;
		const blocks: DocumentBlock[] = [];
		const weights: (number | undefined)[] = [];
		const byNode = new Map<UiNode, number>();
		let remaining = 0;
		let above: UiNode | undefined;
		const sameWidth = previous?.width === width;
		for (const [index, node] of nodes.entries()) {
			const oldIndex = previous?.byNode.get(node);
			const old = oldIndex === undefined ? undefined : previous?.blocks[oldIndex];
			const block = sameWidth ? old?.block : undefined;
			const body = sameWidth ? old?.body : undefined;
			const estimate = body ?? (old?.body || undefined);
			const predecessor = above;
			let lead = 0;
			if (predecessor && estimate !== 0) {
				if (old?.above === predecessor) lead = old.lead;
				else if (body !== undefined) lead = untrack(() => Math.max(0, this.options.separator(predecessor, node)));
				else lead = 1;
			}
			// Carry height across a resize as an estimate; the new layout owns its paint.
			weights.push(estimate === undefined ? undefined : estimate + lead);
			blocks.push({ node, block, lead, above, body });
			byNode.set(node, index);
			if (body === undefined) remaining++;
			if (estimate !== 0) above = node;
		}
		const layout = {
			width,
			nodes,
			blocks,
			byNode,
			rows: new TranscriptRows(weights, previous?.rows.estimate ?? 2),
			remaining,
			warmup: blocks.length - 1,
			seeded: sameWidth && previous.seeded,
		};
		this.#layout = layout;
		return layout;
	}

	#updateExtent(document: Document, index: number): void {
		const { blocks, rows } = document;
		const entry = blocks[index]!;
		const body = entry.body;
		if (body === undefined) return;
		entry.above = blocks[rows.find(rows.start(index) - 1)]?.node;
		entry.lead = entry.above && body > 0 ? Math.max(0, this.options.separator(entry.above, entry.node)) : 0;
		rows.set(index, body + entry.lead);
	}

	#measure(document: Document, index: number, layoutOnly = false): void {
		const { blocks, rows } = document;
		const entry = blocks[index]!;
		const block = this.options.paint(entry.node, document.width, layoutOnly);
		const hadRows = rows.weight(index) > 0;
		if (entry.body === undefined) document.remaining--;
		entry.body = block.rows.length;
		if (!layoutOnly) entry.block = block;
		this.#updateExtent(document, index);
		if (hadRows !== block.rows.length > 0) {
			// A separator joins the nearest nonempty blocks, not necessarily adjacent nodes.
			const next = rows.find(rows.start(index + 1));
			if (next < blocks.length) this.#updateExtent(document, next);
		}
	}

	/** Pause observation while the terminal is lent out. Keep the displayed anchor for restart. */
	pause(): void {
		this.endDrag();
	}

	/** Stop a drag when the pointer is taken away by an overlay or tracking is switched off. */
	endDrag(): void {
		this.#dragging = false;
		this.#scrollbarGrab = undefined;
		this.#stopAutoScroll();
	}

	#stopAutoScroll(): void {
		clearInterval(this.#autoScroll);
		this.#autoScroll = undefined;
		this.#edge = undefined;
	}

	clearSelection(): void {
		this.#selection = undefined;
		this.#dockSelection = undefined;
		this.#lastClick = undefined;
		this.endDrag();
	}

	#saveBookmark(key: string): void {
		const anchor = this.#anchor;
		const document = this.#view?.document;
		const index = anchor && document?.byNode.get(anchor.node);
		if (!anchor || !document || index === undefined) {
			this.#bookmarks.delete(key);
			return;
		}
		const rows = document.blocks[index]?.block?.rows;
		this.#bookmarks.set(key, {
			index,
			kind: anchor.node.kind,
			width: document.width,
			row: anchor.row,
			textOffset: rows && anchor.row >= 0 ? textOffsetAt(rows, anchor) : undefined,
		});
	}

	/** Paint the visible `main` slice into the rows above the dock, leaving any unused space blank. */
	paint(width: number, capacity: number, visible: number, rows: string[], hits: ViewportHit[]): Cell | null {
		// Reserve one column so showing/hiding the chrome never changes transcript wrapping.
		const contentWidth = Math.max(1, width - 1);
		const document = this.#document(contentWidth);
		const previous = this.#view;
		const before = previous?.document ?? document;
		const scope = this.options.surface.mainScrollScope?.();
		const oldScope = this.#scrollScope;
		const switched = scope?.key !== oldScope?.key || scope?.preview !== oldScope?.preview;
		let bookmark: Bookmark | undefined;
		if (switched) {
			if (oldScope && !oldScope.preview) this.#saveBookmark(oldScope.key);
			this.#scrollScope = scope;
			bookmark = scope && this.#bookmarks.get(scope.key);
			this.#anchor = undefined;
			this.clearSelection();
		}
		const geometry = () => {
			const end = document.rows.end;
			const maxTop = Math.max(0, end - Math.max(1, capacity));
			const top = this.#anchor ? Math.min(maxTop, Math.max(0, position(document, this.#anchor).row)) : maxTop;
			const from = top + Math.max(0, Math.min(capacity - visible, end - top - visible));
			return { top, from, to: Math.min(end, from + visible), maxTop };
		};
		const checked = new Set<number>();
		const measure = (index: number): void => {
			if (checked.has(index) || index < 0 || index >= document.blocks.length) return;
			checked.add(index);
			this.#measure(document, index);
		};
		if (bookmark) {
			const { index, kind, width, row, textOffset } = bookmark;
			const entry = document.blocks[index];
			if (entry?.node.kind === kind) {
				measure(index);
				if (entry.block?.rows.length) {
					const cell =
						width === contentWidth || textOffset === undefined
							? { row, col: 0 }
							: cellAtTextOffset(entry.block.rows, textOffset);
					this.#anchor = rebase({ node: entry.node, ...cell }, document, document);
				}
			}
		}
		if (this.#anchor && !switched) {
			const index = document.byNode.get(this.#anchor.node);
			if (index !== undefined) measure(index);
			this.#anchor = rebase(this.#anchor, before, document);
			if (!this.#anchor && document.rows.end > 0) {
				this.#anchor = pointAt(document, Math.min(previous?.top ?? 0, document.rows.end - 1), 0);
			}
		}
		if (before.width !== document.width && this.#selection) {
			for (const point of [this.#selection.anchor, this.#selection.focus]) {
				const index = document.byNode.get(point.node);
				if (index !== undefined) untrack(() => this.#measure(document, index));
			}
		}

		const limit = Math.max(128, capacity + OVERSCAN * 2);
		const fill = (): boolean => {
			// Walk from the edge that must stay visible, changing the other bound as the
			// estimates resolve. A tall block can displace its unpainted neighbours.
			const { top, from: initialFrom, to: initialTo } = geometry();
			if (initialFrom === initialTo) return true;
			let from = initialFrom;
			let to = initialTo;
			const following = !this.#anchor;
			const { rows: heights, blocks } = document;
			for (
				let index = heights.find(following ? heights.end - 1 : top);
				index >= 0 && index < blocks.length;
				index = heights.find(following ? heights.start(index) - 1 : heights.start(index + 1))
			) {
				if (following ? heights.start(index + 1) <= from : heights.start(index) >= to) break;
				if (checked.has(index)) continue;
				if (checked.size >= limit) return false;
				measure(index);
				({ from, to } = geometry());
			}
			return true;
		};
		if (visible > 0) {
			fill();
			const { top, to } = geometry();
			const { blocks, rows: heights } = document;
			const first = heights.find(top);
			const last = heights.find(to - 1);
			// Adjacent blocks make short wheel steps exact. Also observe empty nodes at the tail:
			// a streaming block that currently draws nothing can gain rows without a structural change.
			const nearby = new Set<number>();
			for (let i = 1; i <= OVERSCAN; i++) {
				nearby.add(first - i);
				nearby.add(last + i);
				if (!this.#anchor) nearby.add(blocks.length - i);
			}
			for (const index of nearby) {
				if (blocks[index] && !checked.has(index)) this.#measure(document, index, true);
			}
			if (!document.seeded && checked.size > 0) {
				let sum = 0;
				let sampled = 0;
				for (const index of checked) {
					const body = blocks[index]!.block!.rows.length;
					if (body === 0) continue;
					sum += body;
					sampled++;
				}
				if (sampled > 0) {
					heights.estimate = 1 + Math.round(sum / sampled);
					document.seeded = true;
				}
			}
			if (previous?.document === document && document.remaining > 0) {
				const deadline = performance.now() + REFINE_MS;
				untrack(() => {
					for (let n = 0; document.warmup >= 0 && n < REFINE_BLOCKS; n++) {
						const index = document.warmup--;
						if (blocks[index]!.body === undefined) this.#measure(document, index, true);
						if (performance.now() >= deadline) break;
					}
				});
			}
			if (!fill() || document.remaining > 0) this.options.requestRender();
		}
		if (this.#selection) {
			const anchor = rebase(this.#selection.anchor, before, document, true);
			const focus = rebase(this.#selection.focus, before, document, true);
			this.#selection = anchor && focus ? { ...this.#selection, anchor, focus } : undefined;
			if (!this.#selection) this.endDrag();
		}
		const { top, from, to, maxTop } = geometry();
		const railRows = width > 1 && maxTop > 0 ? visible : 0;
		const thumbRows = Math.min(
			railRows,
			Math.max(1, Math.floor((railRows * capacity) / Math.max(1, document.rows.end))),
		);
		const thumbTop = Math.round((top / Math.max(1, maxTop)) * (railRows - thumbRows));
		const returnRow = railRows > 0 && this.#anchor && top < maxTop ? railRows - 1 : -1;
		this.#view = { document, top, from, to, maxTop, railCol: width - 1, railRows, thumbRows, thumbTop, returnRow };
		const selection = ordered(this.#selection, document);
		const startPoint = selection && position(document, selection[0]);
		const endPoint = selection && position(document, selection[1]);
		let cursor: Cell | null = null;
		const heights = document.rows;
		for (let i = heights.find(from); i < document.blocks.length; i = heights.find(heights.start(i + 1))) {
			const start = heights.start(i) + document.blocks[i]!.lead;
			if (start >= to) break;
			const block = document.blocks[i]!.block;
			if (!block) continue;
			for (let row = Math.max(from, start); row < Math.min(to, start + block.rows.length); row++) {
				let line = block.rows[row - start]!;
				if (line.includes("\x1b7") && hasGraphics(line)) {
					// An image whose first row scrolled off must not jump above the viewport to draw.
					line = line.replace(IMAGE_ANCHOR, (sequence, up: string) => (+up > row - from ? "" : sequence));
				}
				if (textSizedRows(line) > to - row) {
					// A scaled glyph must not extend past `main` into the fixed dock.
					line = tokens(line)
						.map(token => (token.text.startsWith(SIZED) ? sizedText(token.text) : token.text))
						.join("");
				}
				if (startPoint && endPoint)
					line = highlight(line, row, startPoint, endPoint, block.textRows?.[row - start]);
				rows[row - from] = line;
			}
			const placed = start - from;
			if (block.cursor && block.cursor.row + start >= from && block.cursor.row + start < to) {
				cursor = { row: placed + block.cursor.row, col: block.cursor.col };
			}
			for (const hit of block.hits ?? []) {
				if (placed + hit.row + hit.height > 0 && placed + hit.row < visible) {
					hits.push({ hit, top: placed, left: 0, clipAt: visible });
				}
			}
		}
		if (railRows > 0) {
			const theme = this.options.theme();
			for (let row = 0; row < railRows; row++) {
				const control =
					row === returnRow
						? theme.style("accent", "▽")
						: row >= thumbTop && row < thumbTop + thumbRows
							? theme.style("accent", "█")
							: theme.style("muted", "│");
				rows[row] = `${padTo(rows[row]!, contentWidth)}\x1b[0m${control}`;
			}
		}
		return cursor;
	}

	/** Save unhighlighted dock rows for copy, then paint their selection above the viewport's chrome. */
	paintDock(rows: string[], top: number, textRows: readonly (TextRow | undefined)[]): void {
		const dock = rows.slice(top);
		this.#dock = { top, rows: dock, textRows };
		const selection = this.#dockSelection && orderCells(this.#dockSelection);
		if (!selection) return;
		const [start, end] = selection;
		if (end.row >= dock.length) {
			this.#dockSelection = undefined;
			this.endDrag();
			return;
		}
		for (let row = start.row; row <= end.row; row++) {
			rows[row + top] = highlight(dock[row]!, row, start, end, textRows[row]);
		}
	}

	#scroll(delta: number): number | undefined {
		const view = this.#view;
		if (!view || view.document.rows.end === 0) return undefined;
		// Several input reports can arrive before another frame: accumulate on the pending anchor.
		const base = this.#anchor ? position(view.document, this.#anchor).row : view.maxTop;
		const top = Math.max(0, Math.min(view.maxTop, Math.min(view.maxTop, base) + delta));
		this.#setTop(view, top);
		return top;
	}

	#setTop(view: View, top: number): void {
		this.#anchor = top < view.maxTop ? pointAt(view.document, top, 0) : undefined;
	}

	/** Scroll chrome is over the transcript, but only while no layer owns the pointer. */
	chrome(mouse: MouseEvent, row: number): boolean {
		const view = this.#view;
		if (!view || view.railRows === 0 || mouse.action !== "press" || mouse.button !== "left") return false;
		if (mouse.col !== view.railCol || row < 0 || row >= view.railRows) return false;
		if (row === view.returnRow) {
			this.#anchor = undefined;
			return true;
		}
		const inThumb = row >= view.thumbTop && row < view.thumbTop + view.thumbRows;
		this.#scrollbarGrab = inThumb ? row - view.thumbTop : (view.thumbRows - 1) / 2;
		if (!inThumb) this.#dragScrollbar(view, row);
		return true;
	}

	#dragScrollbar(view: View, row: number): void {
		const travel = view.railRows - view.thumbRows;
		if (travel <= 0 || this.#scrollbarGrab === undefined) return;
		const grab = Math.min(view.thumbRows - 1, this.#scrollbarGrab);
		const thumb = Math.max(0, Math.min(travel, row - grab));
		this.#setTop(view, Math.round((thumb * view.maxTop) / travel));
	}

	#copy(): boolean {
		const dock = this.#dock;
		const selection = this.#dockSelection && orderCells(this.#dockSelection);
		if (dock && selection) {
			const [start, end] = selection;
			const chunks: string[] = [];
			for (let row = start.row; row <= end.row && row < dock.rows.length; row++) {
				appendSelection(chunks, dock.rows[row]!, row, start, end, dock.textRows[row]);
			}
			const text = chunks.join("");
			if (!text) return false;
			this.options.copy(text);
			return true;
		}
		const document = this.#view?.document;
		if (!document) return false;
		const points = ordered(this.#selection, document);
		if (!points) return false;
		const [start, end] = points;
		const first = document.byNode.get(start.node)!;
		const last = document.byNode.get(end.node)!;
		const chunks: string[] = [];
		let above: UiNode | undefined;
		for (let index = first; index <= last; index++) {
			const { node, block } = document.blocks[index]!;
			// Copy can span skipped history. Materialize its text without reserving offscreen images.
			const painted = block ?? this.options.paint(node, document.width, true);
			const { rows, textRows } = painted;
			if (rows.length === 0) continue;
			const lead =
				index === first
					? document.blocks[index]!.lead
					: above
						? Math.max(0, this.options.separator(above, node))
						: 0;
			const a = index === first ? start : { row: -lead, col: 0 };
			const b = index === last ? end : { row: rows.length - 1, col: document.width };
			for (let row = Math.max(-lead, a.row); row <= Math.min(rows.length - 1, b.row); row++) {
				appendSelection(chunks, rows[row] ?? "", row, a, b, textRows?.[row]);
			}
			above = node;
		}
		const text = chunks.join("");
		if (!text) return false;
		this.options.copy(text);
		return true;
	}

	/** Selected text takes priority over a focused editor's Ctrl+C binding. */
	copyKey(key: KeyEvent): boolean {
		return key.kind !== "release" && (key.id === "ctrl+c" || key.id === "ctrl+shift+c") && this.#copy();
	}

	key(key: KeyEvent): boolean {
		if (key.kind === "release") return false;
		const page = Math.max(1, (this.#view?.to ?? 1) - (this.#view?.from ?? 0) - 1);
		switch (key.id) {
			case "pageUp":
			case "alt+pageUp":
				this.#scroll(-page);
				return true;
			case "pageDown":
			case "alt+pageDown":
				this.#scroll(page);
				return true;
			case "alt+home":
				this.#scroll(-Infinity);
				return true;
			case "alt+end":
				this.#anchor = undefined;
				return true;
			default:
				return false;
		}
	}

	/** A started selection owns its continuation even over a widget. */
	drag(mouse: MouseEvent, row: number): boolean {
		if (this.#scrollbarGrab !== undefined && this.#view) {
			if (mouse.action === "release") this.endDrag();
			else if (mouse.action === "drag") this.#dragScrollbar(this.#view, row);
			else return false;
			return true;
		}
		if (!this.#dragging) return false;
		if (mouse.action === "release") {
			this.endDrag();
			return true;
		}
		const wheel = wheelDelta(mouse);
		if (mouse.action !== "drag" && wheel === 0) return false;
		if (this.#dockSelection && this.#dock) {
			if (mouse.action !== "drag") return false;
			const dock = this.#dock;
			const at = Math.max(0, Math.min(dock.rows.length - 1, row - dock.top));
			this.#dockSelection = { ...this.#dockSelection, focus: { row: at, col: mouse.col } };
			this.#lastClick = undefined;
			return true;
		}
		const view = this.#view;
		if (!view || !this.#selection) return false;
		const visible = view.to - view.from;
		if (visible <= 0) return false;
		this.#lastClick = undefined;
		const edge = mouse.action === "drag" && (row <= 0 ? -1 : row >= visible - 1 ? 1 : 0);
		if (edge) {
			this.#edge = { row, col: mouse.col, delta: edge };
			this.#autoScroll ??= setInterval(() => {
				const edge = this.#edge;
				if (!edge) return;
				if (this.#extendDrag(edge.row, edge.col, edge.delta)) this.options.requestRender();
			}, AUTO_SCROLL_MS);
		} else if (!wheel) this.#stopAutoScroll();
		this.#extendDrag(row, mouse.col, wheel || edge || 0);
		return true;
	}

	#extendDrag(row: number, col: number, delta: number): boolean {
		const view = this.#view;
		if (!view || !this.#selection || view.to <= view.from) return false;
		const visible = view.to - view.from;
		const top = delta ? (this.#scroll(delta) ?? view.top) : view.top;
		const source = Math.min(
			view.document.rows.end - 1,
			top + view.from - view.top + Math.max(0, Math.min(visible - 1, row)),
		);
		const focus = pointAt(view.document, source, col);
		const previous = this.#selection.focus;
		this.#selection = { ...this.#selection, focus };
		return (
			top !== view.top || focus.node !== previous.node || focus.row !== previous.row || focus.col !== previous.col
		);
	}

	#start<T extends Cell>(point: T, line: string, textRow?: TextRow): Selection<T> {
		const last = this.#lastClick;
		const now = performance.now();
		const node = "node" in point ? point.node : undefined;
		const lastNode = last && "node" in last.point ? last.point.node : undefined;
		const repeated =
			last &&
			now - last.time <= MULTI_CLICK_MS &&
			node === lastNode &&
			last.point.row === point.row &&
			Math.abs(last.point.col - point.col) <= 1;
		const count = repeated ? Math.min(3, last.count + 1) : 1;
		this.#lastClick = { point, time: now, count };
		const range = clickRange(line, point.col, count, textRow);
		this.#dragging = range === undefined;
		return range
			? { anchor: { ...point, col: range[0] }, focus: { ...point, col: range[1] }, explicit: true }
			: { anchor: point, focus: point };
	}

	/** Handle mouse actions no widget in `main` or `dock` claimed. */
	mouse(mouse: MouseEvent, row: number): void {
		const view = this.#view;
		if (!view || mouse.action !== "press") return;
		const delta = wheelDelta(mouse);
		if (delta) {
			this.#lastClick = undefined;
			this.#scroll(delta);
		} else if (mouse.button === "left") {
			this.#selection = undefined;
			this.#dockSelection = undefined;
			const dock = this.#dock;
			if (dock && row >= dock.top && row < dock.top + dock.rows.length) {
				const at = row - dock.top;
				this.#dockSelection = this.#start({ row: at, col: mouse.col }, dock.rows[at]!, dock.textRows[at]);
			} else if (row >= 0 && view.from + row < view.to) {
				const point = pointAt(view.document, view.from + row, mouse.col);
				const block = view.document.blocks[view.document.byNode.get(point.node)!]?.block;
				this.#selection = this.#start(point, block?.rows[point.row] ?? "", block?.textRows?.[point.row]);
			} else this.clearSelection();
		} else if (mouse.button === "right") {
			this.endDrag();
			if (this.#copy()) this.clearSelection();
			else this.options.paste?.();
		}
	}
}

function wheelDelta(mouse: MouseEvent): number {
	if (mouse.action !== "press") return 0;
	return mouse.button === "wheel-up" ? -3 : mouse.button === "wheel-down" ? 3 : 0;
}
